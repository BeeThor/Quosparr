// Command gen-l10n converts the Swift localization tables into
// internal/l10n/tables_gen.go. Run from the repository root:
//
//	go run ./Scripts/gen-l10n
//
// The parser is intentionally strict: any entry it cannot understand aborts
// the run instead of being skipped.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

const coreDir = "Sources/QuosparrCore"

const keyEnumFile = "Preferences.swift"

// tableFiles lists the Swift sources scanned for tables.
var tableFiles = []string{
	"LocalizationTables.swift",
	"LocalizationTables+zhHant.swift",
	"LocalizationTables+ko.swift",
	"LocalizationTables+ja.swift",
	"LocalizationTables+ru.swift",
	"LocalizationTables+fr.swift",
}

// swiftTables maps the Swift table identifier to the Go Language constant, in
// output order.
var swiftTables = []struct{ swift, goName string }{
	{"en", "English"},
	{"zhHans", "SimplifiedChinese"},
	{"zhHant", "TraditionalChinese"},
	{"ko", "Korean"},
	{"ja", "Japanese"},
	{"ru", "Russian"},
	{"fr", "French"},
}

type entry struct{ key, value string }

func main() {
	root := flag.String("root", ".", "repository root")
	out := flag.String("out", "internal/l10n/tables_gen.go", "output file, relative to root")
	flag.Parse()
	if err := run(*root, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-l10n:", err)
		os.Exit(1)
	}
}

func run(root, out string) error {
	src, err := generate(root)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, out), src, 0o644)
}

// generate returns the formatted Go source for the generated file.
func generate(root string) ([]byte, error) {
	keys, err := readKeyEnum(filepath.Join(root, coreDir, keyEnumFile))
	if err != nil {
		return nil, err
	}
	keySet := map[string]bool{}
	for _, k := range keys {
		keySet[k] = true
	}
	tables := map[string][]entry{}
	for _, f := range tableFiles {
		data, err := os.ReadFile(filepath.Join(root, coreDir, f))
		if err != nil {
			return nil, err
		}
		found, err := parseTables(f, string(data))
		if err != nil {
			return nil, err
		}
		for name, entries := range found {
			if _, dup := tables[name]; dup {
				return nil, fmt.Errorf("%s: table %q defined twice", f, name)
			}
			tables[name] = entries
		}
	}
	known := map[string]bool{}
	for _, t := range swiftTables {
		known[t.swift] = true
		entries, ok := tables[t.swift]
		if !ok {
			return nil, fmt.Errorf("table %q not found in any source file", t.swift)
		}
		for _, e := range entries {
			if !keySet[e.key] {
				return nil, fmt.Errorf("table %q: key %q is not a case of L10nKey", t.swift, e.key)
			}
		}
	}
	for name := range tables {
		if !known[name] {
			return nil, fmt.Errorf("table %q has no language mapping", name)
		}
	}
	return render(keys, tables)
}

func render(keys []string, tables map[string][]entry) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by Scripts/gen-l10n; DO NOT EDIT.\n")
	b.WriteString("//\n// Sources: " + coreDir + "/" + keyEnumFile + ",\n")
	b.WriteString("// " + strings.Join(tableFiles, ",\n// ") + "\n\n")
	b.WriteString("package l10n\n\n")

	idents := map[string]string{}
	b.WriteString("// Localization keys, in the order of the Swift L10nKey enum.\nconst (\n")
	for _, k := range keys {
		id := "Key" + strings.ToUpper(k[:1]) + k[1:]
		if other, dup := idents[id]; dup {
			return nil, fmt.Errorf("keys %q and %q map to the same identifier %s", other, k, id)
		}
		idents[id] = k
		fmt.Fprintf(&b, "\t%s Key = %s\n", id, strconv.Quote(k))
	}
	b.WriteString(")\n\n// allKeys lists every key in Swift enum order.\nvar allKeys = []Key{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\tKey%s%s,\n", strings.ToUpper(k[:1]), k[1:])
	}
	b.WriteString("}\n\n// tables holds the translations as written in the Swift sources.\nvar tables = map[Language]map[Key]string{\n")
	for _, t := range swiftTables {
		fmt.Fprintf(&b, "\t%s: {\n", t.goName)
		for _, e := range tables[t.swift] {
			fmt.Fprintf(&b, "\t\tKey%s%s: %s,\n", strings.ToUpper(e.key[:1]), e.key[1:], strconv.Quote(e.value))
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w", err)
	}
	return out, nil
}

// ---- Swift parsing ----

type scanner struct {
	file string
	s    string
	pos  int
}

func (sc *scanner) line() int { return strings.Count(sc.s[:sc.pos], "\n") + 1 }

func (sc *scanner) errf(format string, a ...any) error {
	return fmt.Errorf("%s:%d: %s", sc.file, sc.line(), fmt.Sprintf(format, a...))
}

func (sc *scanner) eof() bool { return sc.pos >= len(sc.s) }

// skipSpace skips whitespace and // line comments.
func (sc *scanner) skipSpace() {
	for !sc.eof() {
		r, n := utf8.DecodeRuneInString(sc.s[sc.pos:])
		switch {
		case unicode.IsSpace(r):
			sc.pos += n
		case strings.HasPrefix(sc.s[sc.pos:], "//"):
			for !sc.eof() && sc.s[sc.pos] != '\n' {
				sc.pos++
			}
		default:
			return
		}
	}
}

func (sc *scanner) consume(prefix string) bool {
	if strings.HasPrefix(sc.s[sc.pos:], prefix) {
		sc.pos += len(prefix)
		return true
	}
	return false
}

func isIdentChar(r byte) bool {
	return r == '_' || r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z'
}

func (sc *scanner) ident() (string, bool) {
	start := sc.pos
	for !sc.eof() && isIdentChar(sc.s[sc.pos]) {
		sc.pos++
	}
	return sc.s[start:sc.pos], sc.pos > start
}

// stringLiteral parses a single-line Swift string literal.
func (sc *scanner) stringLiteral() (string, error) {
	if sc.eof() || sc.s[sc.pos] != '"' {
		return "", sc.errf("expected string literal")
	}
	if strings.HasPrefix(sc.s[sc.pos:], `"""`) {
		return "", sc.errf("multi-line string literals are not supported")
	}
	sc.pos++
	var b strings.Builder
	for {
		if sc.eof() || sc.s[sc.pos] == '\n' {
			return "", sc.errf("unterminated string literal")
		}
		c := sc.s[sc.pos]
		switch c {
		case '"':
			sc.pos++
			return b.String(), nil
		case '\\':
			sc.pos++
			if err := sc.escape(&b); err != nil {
				return "", err
			}
		default:
			b.WriteByte(c)
			sc.pos++
		}
	}
}

func (sc *scanner) escape(b *strings.Builder) error {
	if sc.eof() {
		return sc.errf("dangling backslash")
	}
	c := sc.s[sc.pos]
	sc.pos++
	switch c {
	case '\\', '"', '\'':
		b.WriteByte(c)
	case 'n':
		b.WriteByte('\n')
	case 't':
		b.WriteByte('\t')
	case 'r':
		b.WriteByte('\r')
	case '0':
		b.WriteByte(0)
	case 'u':
		if !sc.consume("{") {
			return sc.errf(`malformed \u escape`)
		}
		end := strings.IndexByte(sc.s[sc.pos:], '}')
		if end < 0 {
			return sc.errf(`malformed \u escape`)
		}
		n, err := strconv.ParseUint(sc.s[sc.pos:sc.pos+end], 16, 32)
		if err != nil || !utf8.ValidRune(rune(n)) {
			return sc.errf(`invalid \u escape`)
		}
		b.WriteRune(rune(n))
		sc.pos += end + 1
	default:
		return sc.errf(`unsupported escape \%c (string interpolation is not allowed in tables)`, c)
	}
	return nil
}

// parseTables finds every `static let NAME: [L10nKey: String] = [ ... ]`.
func parseTables(file, src string) (map[string][]entry, error) {
	const marker = "static let "
	out := map[string][]entry{}
	sc := &scanner{file: file, s: src}
	for {
		i := strings.Index(sc.s[sc.pos:], marker)
		if i < 0 {
			break
		}
		sc.pos += i + len(marker)
		name, ok := sc.ident()
		if !ok {
			return nil, sc.errf("expected table name")
		}
		sc.skipSpace()
		if !sc.consume(": [L10nKey: String] = [") {
			return nil, sc.errf("table %q: unexpected declaration", name)
		}
		entries, err := sc.parseEntries()
		if err != nil {
			return nil, fmt.Errorf("table %q: %w", name, err)
		}
		out[name] = entries
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no tables found", file)
	}
	return out, nil
}

func (sc *scanner) parseEntries() ([]entry, error) {
	var entries []entry
	seen := map[string]bool{}
	for {
		sc.skipSpace()
		if sc.consume("]") {
			return entries, nil
		}
		if !sc.consume(".") {
			return nil, sc.errf("expected `.key:` or `]`")
		}
		key, ok := sc.ident()
		if !ok {
			return nil, sc.errf("expected key name")
		}
		if seen[key] {
			return nil, sc.errf("duplicate key %q", key)
		}
		seen[key] = true
		sc.skipSpace()
		if !sc.consume(":") {
			return nil, sc.errf("key %q: expected `:`", key)
		}
		sc.skipSpace()
		val, err := sc.stringLiteral()
		if err != nil {
			return nil, fmt.Errorf("key %q: %w", key, err)
		}
		sc.skipSpace()
		if !sc.consume(",") && !(sc.pos < len(sc.s) && sc.s[sc.pos] == ']') {
			return nil, sc.errf("key %q: expected `,` after value", key)
		}
		entries = append(entries, entry{key, val})
	}
}

// readKeyEnum returns the case names of `enum L10nKey` in declaration order.
func readKeyEnum(path string) ([]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	sc := &scanner{file: filepath.Base(path), s: string(data)}
	const header = "enum L10nKey: String, CaseIterable, Sendable {"
	i := strings.Index(sc.s, header)
	if i < 0 {
		return nil, fmt.Errorf("%s: L10nKey enum not found", sc.file)
	}
	sc.pos = i + len(header)
	var keys []string
	seen := map[string]bool{}
	for {
		sc.skipSpace()
		if sc.consume("}") {
			break
		}
		if !sc.consume("case") {
			return nil, sc.errf("expected `case` or `}` in L10nKey")
		}
		for {
			sc.skipSpace()
			name, ok := sc.ident()
			if !ok {
				return nil, sc.errf("expected case name")
			}
			if seen[name] {
				return nil, sc.errf("duplicate case %q", name)
			}
			seen[name] = true
			keys = append(keys, name)
			sc.skipSpace()
			if sc.pos < len(sc.s) && sc.s[sc.pos] == '=' {
				return nil, sc.errf("case %q has a custom raw value, not supported", name)
			}
			if !sc.consume(",") {
				break
			}
		}
	}
	if len(keys) == 0 {
		return nil, fmt.Errorf("%s: L10nKey enum is empty", sc.file)
	}
	return keys, nil
}
